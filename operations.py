
n = int(input("Введите число n: ")) # Ввод числа
a = 0 # Счётчик начинается с 0
if n >= 1 and n <= 100000: # Область допустимых значений числа
    while n > 0:
        n = n - 3   # Вычитаем тройку на каждом шаге 
        a += 1      # Прибавляем 1 к счетчику
    print("Число операция до нуля",a) # вывод результата 
else:       
    print("ошибка") # Если число не принадлежит [1;100000]